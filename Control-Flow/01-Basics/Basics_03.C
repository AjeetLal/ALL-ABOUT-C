// PROGRAM TO UNDERSTAND VARIABLES AND BASIC DATA TYPES//
//HERE WE ARE USING DIFFRENT DATA TYPES IN A SINGLE PROGRAM//


#include<stdio.h>
int main()
{
    int Age = 19;
    float Percentage = 66.87;
    char Grade = 'A';

    printf("the age is: %d\n", Age);
    printf("the percentage is: %f\n", Percentage);
    printf("the grade is: %c\n", Grade);
    return 0;
}